"""Maintenance-only catalog schema. Runtime provisioning belongs to the host."""
from collections.abc import Callable
from typing import Any

from ..search import compact, normalize


_MIGRATION_LOCK = 0x41544F4D434154  # Stable across processes and future schema versions.
_VERSION = 5

_SCHEMA_V1 = """
CREATE SCHEMA IF NOT EXISTS atom_search AUTHORIZATION atom_bootstrap;
REVOKE ALL ON SCHEMA atom_search FROM PUBLIC;
CREATE TABLE atom_search.schema_migrations (
    version integer PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE atom_search.catalogs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    state text NOT NULL CHECK (state IN ('staging','active','retired')),
    generation bigint NOT NULL DEFAULT 0 CHECK (generation >= 0)
);
CREATE UNIQUE INDEX one_active_catalog ON atom_search.catalogs (state) WHERE state='active';
CREATE TABLE atom_search.sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    catalog_id bigint NOT NULL REFERENCES atom_search.catalogs(id),
    path text NOT NULL, last_attempt timestamptz, last_success timestamptz,
    status text NOT NULL CHECK (status IN ('new','scanning','complete','partial','unavailable','cancelled')),
    error text, UNIQUE(catalog_id,path)
);
CREATE TABLE atom_search.directories (
    source_id bigint NOT NULL REFERENCES atom_search.sources(id) ON DELETE CASCADE,
    relative_path text NOT NULL, PRIMARY KEY(source_id,relative_path)
);
CREATE TABLE atom_search.files (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    source_id bigint NOT NULL REFERENCES atom_search.sources(id) ON DELETE CASCADE,
    relative_path text NOT NULL, parent text NOT NULL, name text NOT NULL,
    size bigint NOT NULL CHECK (size >= 0), modified_ns bigint NOT NULL,
    revision bigint NOT NULL CHECK (revision >= 1),
    compact_name text NOT NULL, compact_stem text NOT NULL, UNIQUE(source_id,relative_path)
);
CREATE INDEX files_source_parent ON atom_search.files(source_id,parent);
CREATE TABLE atom_search.embedding_models (
    model_key text PRIMARY KEY, dimension integer NOT NULL CHECK (dimension=384),
    input_schema text NOT NULL, manifest_digest text NOT NULL
);
CREATE TABLE atom_search.file_embeddings (
    file_id bigint NOT NULL REFERENCES atom_search.files(id) ON DELETE CASCADE,
    model_key text NOT NULL REFERENCES atom_search.embedding_models(model_key),
    file_revision bigint NOT NULL CHECK (file_revision >= 1), input_hash text NOT NULL,
    embedding public.vector(384) NOT NULL, PRIMARY KEY(file_id,model_key)
);
INSERT INTO atom_search.catalogs(state,generation) VALUES ('active',0);
"""

