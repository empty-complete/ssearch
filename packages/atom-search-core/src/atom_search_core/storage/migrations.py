def _backfill_v2(connection):
    # Bounded batches avoid loading an existing catalog into Python at once.
    # Use the same Python Unicode normalization as live reconcile and queries;
    # SQL lower() in the pinned C-locale runtime is not equivalent.
    last_id = 0
    while True:
        batch = connection.execute("""SELECT id,name,relative_path FROM atom_search.files
            WHERE id>%s ORDER BY id LIMIT 500""", (last_id,)).fetchall()
        if not batch:
            break
        for file_id, name, path in batch:
            connection.execute("""UPDATE atom_search.files SET compact_name=%s,compact_stem=%s,compact_path=%s,
                fts_russian=setweight(to_tsvector('russian',%s),'A') || setweight(to_tsvector('russian',%s),'B'),
                fts_simple=setweight(to_tsvector('simple',%s),'A') || setweight(to_tsvector('simple',%s),'B')
                WHERE id=%s""", (compact(name), compact(name.rsplit('.', 1)[0]), compact(path),
                                  normalize(name), normalize(path), normalize(name), normalize(path), file_id))
        last_id = batch[-1][0]
    connection.execute("""ALTER TABLE atom_search.files ALTER COLUMN compact_path SET NOT NULL,
        ALTER COLUMN fts_russian SET NOT NULL, ALTER COLUMN fts_simple SET NOT NULL""")


def apply_catalog_migrations(connection_factory: Callable[[], Any]) -> int:
    """Apply supported migrations atomically using the maintenance factory.

    Inspect versions under the same advisory lock as DDL. A future schema is
    rejected before grants or any other writes; P0 alone installs extensions.
    """
    with connection_factory() as connection:
        connection.execute("SELECT pg_advisory_xact_lock(%s)", (_MIGRATION_LOCK,))
        if connection.execute("SELECT current_user").fetchone()[0] != "atom_bootstrap":
            raise ValueError("Catalog migrations require maintenance role atom_bootstrap")
        owner = connection.execute("""SELECT pg_get_userbyid(nspowner)
            FROM pg_namespace WHERE nspname='atom_search'""").fetchone()
        if owner is not None and owner[0] != "atom_bootstrap":
            raise ValueError("Unexpected atom_search schema owner")
        version = 0
        if connection.execute("SELECT to_regclass('atom_search.schema_migrations')").fetchone()[0]:
            version = connection.execute("SELECT COALESCE(max(version),0) FROM atom_search.schema_migrations").fetchone()[0]
        if version > _VERSION:
            raise ValueError("Catalog schema version is newer than this adapter")
        if version not in (0, 1, 2, 3, 4, _VERSION):
            raise ValueError("Unsupported catalog schema version")
        if connection.execute("SHOW server_version_num").fetchone()[0] != "180006":
            raise ValueError("Catalog requires PostgreSQL 18.6")
        extension = connection.execute("""SELECT e.extversion,n.nspname FROM pg_extension e
            JOIN pg_namespace n ON n.oid=e.extnamespace WHERE e.extname='vector'""").fetchone()
        if extension != ("0.8.7", "public"):
            raise ValueError("Catalog requires P0-provisioned public vector 0.8.7")
        if version == 0:
            connection.execute(_SCHEMA_V1)
            connection.execute("INSERT INTO atom_search.schema_migrations(version) VALUES (1)")
        if version < 2:
            connection.execute(_SCHEMA_V2)
            _backfill_v2(connection)
            connection.execute("INSERT INTO atom_search.schema_migrations(version) VALUES (2)")
        if version < 3:
            connection.execute(_SCHEMA_V3)
            connection.execute("INSERT INTO atom_search.schema_migrations(version) VALUES (3)")
        if version < 4:
            connection.execute(_SCHEMA_V4)
            connection.execute("INSERT INTO atom_search.schema_migrations(version) VALUES (4)")
        if version < 5:
            connection.execute(_SCHEMA_V5)
            connection.execute("INSERT INTO atom_search.schema_migrations(version) VALUES (5)")
        connection.execute(_GRANTS)
    return _VERSION
